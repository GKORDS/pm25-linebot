def get_level(pm25):
    """
    รับค่า PM 2.5 (ตัวเลข) แล้วคืนค่า dict ของระดับคุณภาพอากาศที่ตรงกับช่วงนั้น
    ถ้าค่ามากกว่าทุกช่วงที่มี max_pm จะคืนระดับสุดท้าย (สีแดง)
    """
    pm = float(pm25)
    for level in AQI_LEVELS:
        if level["max_pm"] is None or pm <= level["max_pm"]:
            return level
    return AQI_LEVELS[-1]


def is_over_standard(pm25):
    """ค่าฝุนเกินมาตรฐาน 37.5 หรือไม่ (ใช้ตัดสินใจส่งการแจ้งเตือนอัตโนมัติ)"""
    try:
        return float(pm25) > STANDARD
    except (TypeError, ValueError):
        return False


def level_advice(pm25):
    """
    ฟังก์ชันแบบย่อ (ตามตัวอย่างในภาคผนวกของรายงาน)
    คืนค่า (ข้อความระดับสี, คำแนะนำ) เพื่อใช้สร้างข้อความตอบกลับแบบข้อความล้วน
    """
    lv = get_level(pm25)
    return f"{lv['color_th']} {lv['meaning']}", lv["advice"]
