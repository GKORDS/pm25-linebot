# รหัสสถานี -> ชื่อย่อที่แสดงให้ผู้ใช้เห็น (เน้นพื้นที่กรุงเทพฯ และนนทบุรี ตามขอบเขตโครงงาน)
STATIONS = {
    # --- กรุงเทพมหานคร ---
    "50t": "รพ.จุฬาฯ (ปทุมวัน) กทม.",
    "54t": "การเคหะดินแดง (ดินแดง) กทม.",
    "02t": "ม.ราชภัฏบ้านสมเด็จฯ (ธนบุรี) กทม.",
    "05t": "กรมอุตุฯ บางนา กทม.",
    # --- นนทบุรี ---
    "13t": "กรมควบคุมโรค (เมืองนนทบุรี)",
    "22t": "มสธ. (ปากเกร็ด) นนทบุรี",
}


def name_of(station_id, fallback=None):
    """คืนชื่อย่อของสถานีจากรหัส ถ้าไม่รู้จักจะคืน fallback หรือรหัสเดิม"""
    return STATIONS.get(station_id, fallback if fallback is not None else station_id)


def is_known(station_id):
    return station_id in STATIONS
